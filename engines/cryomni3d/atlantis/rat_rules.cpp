RatRules::RatRules() : clockTicked(0), result(0) {
	memcpy(mem, kRatInitial, kMemSize);
}

float RatRules::f(uint32 a) const {
	uint32 v = (uint32)i(a);
	float r;
	memcpy(&r, &v, 4);
	return r;
}

void RatRules::setF(uint32 a, float v) {
	uint32 u;
	memcpy(&u, &v, 4);
	setI(a, (int32)u);
}

void RatRules::reset() {
	for (int r = 0; r < kNumRecords; r++) {
		setB(rec(r, kAbove), 0);
		setB(rec(r, kActive), 1);
		setB(rec(r, kPressed), 0);
		setS(rec(r, kFrame), s(rec(r, kRest)));
	}
	setB(0x004969c9, 0);    // record 0 inactive, pressed
	setB(0x00496aaf, 1);
	setB(0x004969ca, 1);
	setB(0x00496b68, 2);    // record 18 in its middle position
	setB(0x00496b7f, 1);    // record 19 turns one way
	setB(0x00496b7e, 1);
	setB(0x00496c07, 1);    // records 25..27 drawn above the rat
	setB(0x00496c1e, 1);
	setB(0x00496c35, 1);
	setI(0x00496cc0, 0);
	setS(0x00496abd, (int)f(0x00496cb4));   // FUN_00451d6e truncates
	setI(0x00496cb8, 0x3dc30c31);
}

void RatRules::clicks(int mx, int my, bool click, bool held, Common::Array<int> &sounds) {
	if (click) {
		// FUN_0043500c: a click at the side edges leaves (result 1).
		if (mx < 10 || mx > 600)
			result = 1;   // [0x00496d0c]
		struct Box {
			static bool hit(int x, int y, int mx, int my) {
				return x - 10 < mx && mx < x + 0x3c && y < my && my < y + 0x1e;
			}
		};
		if (Box::hit(s(rec(7, kX)), s(rec(7, kY)), mx, my) && b(0x004969c2) == 0 && b(rec(7, kActive)) == 1) {
			sounds.push_back(s(rec(7, kSound)));
			if (b(0x00496b7f) == 1) {
				setB(0x00496b7f, 2);
				setS(rec(7, kFrame), s(rec(7, kPressedFrame)));
			} else {
				setB(0x00496b7f, 1);
				setS(rec(7, kFrame), s(rec(7, kRest)));
			}
		}
		if (Box::hit(s(rec(9, kX)), s(rec(9, kY)), mx, my) && b(0x004969c2) == 0 && b(rec(9, kActive)) == 1)
			sounds.push_back(s(rec(9, kSound)));
		if (Box::hit(s(rec(6, kX)), s(rec(6, kY)), mx, my) && b(0x004969c2) == 0 && b(rec(6, kActive)) == 1)
			sounds.push_back(s(rec(6, kSound)));
	}

	if (held) {
		for (int r = 1; r <= 10; r++) {
			const int x = s(rec(r, kX)), y = s(rec(r, kY));
			if (!(x - 10 < mx && mx < x + 0x32 && y < my && my < y + 0x1e))
				continue;
			if (b(0x004969c2) != 0 || b(rec(r, kActive)) != 1 || b(rec(r, kPressed)) != 0)
				continue;
			const int snd = s(rec(r, kSound));
			const bool playable = snd >= 0 && snd < 0x19;
			switch (r) {
			case 1: case 2: case 4: case 8: {
				if (playable)
					sounds.push_back(snd);
				setB(rec(r, kPressed), 1);
				setS(rec(r, kFrame), s(rec(r, kPressedFrame)));
				const int p = s(rec(r, kPartner));
				setB(rec(p, kPressed), 1);
				setS(rec(p, kFrame), s(rec(p, kPressedFrame)));
				break;
			}
			case 5: {
				if (playable)
					sounds.push_back(snd);
				setS(rec(r, kFrame), s(rec(r, kPressedFrame)));
				setB(rec(r, kPressed), 1);
				setB(rec(s(rec(r, kPartner)), kPressed), 1);
				break;
			}
			case 3:
				if (playable)
					sounds.push_back(snd);
				setB(rec(r, kPressed), 1);
				break;
			case 10:
				if (b(0x004969c3) == 0 && playable)
					sounds.push_back(snd);
				setB(0x00496aaf, 0);
				setB(0x00496ab0, 1);
				setB(0x004969c3, 1);
				break;
			default:
				break;
			}
		}
	} else {
		for (int r = 1; r <= 10; r++) {
			if (b(rec(r, kActive)) != 1 || !(r == 1 || r == 2 || r == 4 || r == 8))
				continue;
			setB(rec(r, kPressed), 0);
			setS(rec(r, kFrame), s(rec(r, kRest)));
			const int p = s(rec(r, kPartner));
			setB(rec(p, kPressed), 0);
			setS(rec(p, kFrame), s(rec(p, kRest)));
		}
	}

	if (held) {
		// Record 9 held: every second frame the wheel (its partner) turns.
		int x = s(rec(9, kX)), y = s(rec(9, kY));
		if (x - 10 < mx && mx < x + 0x32 && y < my && my < y + 0x28) {
			if (i(0x00496ccc) == 1) {
				setI(0x00496ccc, 0);
				setB(rec(9, kPressed), 1);
				setS(rec(9, kFrame), s(rec(9, kPressedFrame)));
				const int p = s(rec(9, kPartner));
				setS(rec(p, kFrame), s(rec(p, kFrame)) + 1);
				if (s(rec(p, kFrame)) > s(rec(p, kPressedFrame)))
					setS(rec(p, kFrame), s(rec(p, kPressedFrame)));
			} else {
				setI(0x00496ccc, 1);
			}
		}
		x = s(rec(6, kX));
		y = s(rec(6, kY));
		if (x - 10 < mx && mx < x + 0x32 && y < my && my < y + 0x28) {
			setB(rec(6, kPressed), 1);
			setS(rec(6, kFrame), s(rec(6, kPressedFrame)));
			const int p = s(rec(6, kPartner));
			setS(rec(p, kFrame), s(rec(p, kPressedFrame)));
		}
	} else {
		setB(rec(9, kPressed), 0);
		setS(rec(9, kFrame), s(rec(9, kRest)));
		int p = s(rec(9, kPartner));
		setS(rec(p, kFrame), s(rec(p, kRest)));
		setB(rec(6, kPressed), 0);
		setS(rec(6, kFrame), s(rec(6, kRest)));
		p = s(rec(6, kPartner));
		setS(rec(p, kFrame), s(rec(p, kRest)));
	}
}

void RatRules::animateRat() {
	if (b(0x00496ca5) == 1)
		setB(0x00496ca5, 6);
	if (b(0x00496ca5) == 0)
		setI(0x00496cd0, i(0x00496cd0) + 1);
	const uint32 e = 0x00496c7a + 6 * b(0x00496ca5);   // {first, last, current}
	switch (b(0x00496ca4)) {
	case 0:
		if (b(0x00496ca5) == 0) {
			if (i(0x00496cd0) > 10) {
				setS(e + 4, s(e + 4) + 1);
				setI(0x00496cd0, 0);
			}
		} else {
			setS(e + 4, s(e + 4) + 1);
		}
		if (s(e + 4) > s(e + 2))
			setS(e + 4, s(e));
		break;
	case 1:
		setS(e + 4, s(e));
		break;
	case 2:
		setS(e + 4, s(e + 4) + 1);
		if (s(e + 4) > s(e + 2))
			setS(e + 4, s(e));
		break;
	default:
		break;
	}
}

void RatRules::updateRecord(int r, uint32 ticks, Common::Array<int> &sounds) {
	if (r == 9 || r == 6 || r == 5)
		return;
	if (b(rec(r, kPressed)) == 0)
		return;
	const uint16 kind = (uint16)s(rec(r, kKind));
	if (kind > 3)
		return;
	switch (kind) {
	case 0:
		if (r == 0x12 && i(0x00496cc0) == 0) {
			if (clockTicked == 1) {
				// Record 18 steps with the clock, turning at its ends.
				setS(0x00496b75, s(0x00496b75) + (int16)i(0x00496cbc));
				if (s(0x00496b75) > s(0x00496b73)) {
					setS(0x00496b75, s(0x00496b71) + 1);
					setI(0x00496cbc, -1);
				} else if (s(0x00496b75) < s(0x00496b71)) {
					setS(0x00496b75, s(0x00496b73) - 1);
					setI(0x00496cbc, 1);
				}
				if (s(0x00496b75) == s(0x00496b71))
					setB(0x00496b68, 1);
				else if (s(0x00496b75) == s(0x00496b73))
					setB(0x00496b68, 3);
				else if (s(0x00496b75) == s(0x00496b73) - 1)
					setB(0x00496b68, 2);
				clockTicked = 0;
			}
			return;
		}
		if (r == 0x12)
			return;
		setS(rec(r, kFrame), b(rec(r, kPressed)) == 0 ? s(rec(r, kRest)) : s(rec(r, kPressedFrame)));
		return;
	case 1:
		if (r == 0x13) {
			if (b(0x00496b7f) == 1) {
				setS(0x00496b8c, s(0x00496b8c) + 1);
				if (s(0x00496b8c) > s(0x00496b8a))
					setS(0x00496b8c, s(0x00496b88));
			} else if (b(0x00496b7f) == 2) {
				setS(0x00496b8c, s(0x00496b8c) - 1);
				if (s(0x00496b8c) < s(0x00496b88))
					setS(0x00496b8c, s(0x00496b8a));
			}
			return;
		}
		setS(rec(r, kCounter), s(rec(r, kCounter)) + 1);
		if (s(rec(r, kCounter)) > 0xf) {
			setB(rec(r, kPressed), 0);
			setS(rec(r, kFrame), s(rec(r, kFrame)) - 1);
		}
		return;
	case 2:
		if (r == 0) {
			// The clock: a step every 0x5dc ticks once the run started.
			if (ticks > (uint32)i(0x004969c4) && b(0x004969c3) == 1) {
				setI(0x004969c4, (int32)(ticks + 0x5dc));
				setS(0x004969d7, s(0x004969d7) + 1);
				if (i(0x00496cb0) != 0) {
					setF(0x00496cb4, f(0x00496cb4) - f(0x00496cb8));
					setS(0x00496abd, (int)((double)f(0x00496cb4) + 0.5));
				}
				if (s(0x004969d7) > s(0x004969d5)) {
					setB(0x004969c2, 1);
					result = 0xa;
					setS(0x004969d7, s(0x004969d5));
				}
				clockTicked = 1;
			}
			return;
		}
		setS(rec(r, kFrame), s(rec(r, kFrame)) + 1);
		if (s(rec(r, kFrame)) > s(rec(r, kPressedFrame))) {
			setS(rec(r, kFrame), s(rec(r, kPressedFrame)));
			if (r == 10) {
				setI(0x00496cb0, 1);
				setB(0x00496aaf, 1);
				setB(0x00496ab0, 0);
			} else if (r == 0x10) {
				setB(0x00496b39, 0);
			} else {
				setB(rec(r, kPressed), 0);
			}
		}
		return;
	case 3:
		if (s(rec(r, kFrame)) >= s(rec(r, kPressedFrame))) {
			setS(rec(r, kFrame), s(rec(r, kPressedFrame)));
			if (r == 0x10) {
				setI(0x00496cd4, i(0x00496cd4) + 1);
				if (i(0x00496cd4) > 0x32) {
					setS(0x00496a4a, s(0x00496a46));
					setB(0x00496a3d, 0);
					setB(0x00496b3a, 0);
					setS(0x00496b47, s(0x00496b43));
					setI(0x00496cd4, 0);
				}
			} else if (r == 10) {
				setB(rec(r, kPressed), 2);
			} else {
				setB(rec(r, kPressed), 0);
				setS(rec(r, kFrame), s(rec(r, kRest)));
			}
		} else {
			setS(rec(r, kFrame), s(rec(r, kFrame)) + 1);
		}
		return;
	default:
		break;
	}
	(void)sounds;
}

void RatRules::frameUpdates(uint32 ticks, Common::Array<int> &sounds) {
	animateRat();
	for (int r = 0; r < 28; r++) {
		if (r == 10) {
			if (b(rec(10, kActive)) == 0)
				updateRecord(10, ticks, sounds);
		} else if (r == 18) {
			if (b(rec(18, kActive)) == 1)
				updateRecord(18, ticks, sounds);
		} else if (b(rec(r, kActive)) == 1) {
			updateRecord(r, ticks, sounds);
		}
	}
}

