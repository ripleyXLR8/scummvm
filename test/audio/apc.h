class APCDecoderTestSuite : public CxxTest::TestSuite {
	void check(const byte *in, uint inSize, const int16 *expected, uint outSize,
	           bool stereo, int32 left, int32 right) {
		byte header[32];
		memcpy(header, "CRYO_APC1.20", 12);
		WRITE_LE_UINT32(header + 12, outSize / (stereo ? 2 : 1));
		WRITE_LE_UINT32(header + 16, 22050);
		WRITE_LE_UINT32(header + 20, (uint32)left);
		WRITE_LE_UINT32(header + 24, (uint32)right);
		WRITE_LE_UINT32(header + 28, stereo ? 1 : 0);
		Common::MemoryReadStream headerStream(header, sizeof(header));

		// The APC stream queues its output in a QueuingAudioStream, which
		// needs an OSystem for its mutex.
		Common::install_null_g_system();

		Audio::PacketizedAudioStream *s = Audio::makeAPCStream(headerStream);
		TS_ASSERT(s != nullptr);
		s->queuePacket(new Common::MemoryReadStream(in, inSize));
		s->finish();

		int16 *out = new int16[outSize];
		TS_ASSERT_EQUALS(s->readBuffer(out, outSize), (int)outSize);
		for (uint i = 0; i < outSize; i++)
			TS_ASSERT_EQUALS(out[i], expected[i]);

		delete[] out;
		delete s;
		Common::uninstall_null_g_system();
	}

public:
	void test_stereo() {
		check(apc_stereo_in, sizeof(apc_stereo_in), apc_stereo_out, ARRAYSIZE(apc_stereo_out), true, -8, -6);
	}

	void test_mono() {
		check(apc_mono_in, sizeof(apc_mono_in), apc_mono_out, ARRAYSIZE(apc_mono_out), false, 120, 0);
	}

	// The predictor goes beyond the 16-bit range: output samples wrap, but
	// decoding continues from the full-width predictor.
	void test_predictor_overflow() {
		check(apc_overflow_in, sizeof(apc_overflow_in), apc_overflow_out, ARRAYSIZE(apc_overflow_out), true, 30000, -30000);
	}
};
