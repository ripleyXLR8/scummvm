inline void stateFor(const SynthCase &c, ScriptsTest::VarState &st) {
	st.vars.clear();
	st.inventory.clear();
	for (uint i = 0; i < ARRAYSIZE(c.vars) && c.vars[i].name; i++) {
		Common::String k(c.vars[i].name);
		k.toLowercase();
		st.vars[k] = c.vars[i].value;
	}
	for (uint i = 0; i < ARRAYSIZE(c.inventory) && c.inventory[i]; i++)
		st.inventory.push_back(c.inventory[i]);
}

