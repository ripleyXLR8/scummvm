class ScriptsConEvalTestSuite : public CxxTest::TestSuite {
public:
	void setUp() override { Common::install_null_g_system(); }
	void tearDown() override { Common::uninstall_null_g_system(); }

	// The copy of evalSelSection must still match the port source.
	void test_eval_copy_is_current() {
		Common::String src = AtlantisTest::configValue("src");
		if (src.empty()) {
			TS_WARN("scripts_con_eval: no src= in atlantis_test.cfg, copy check skipped");
			return;
		}
		Common::FSNode node(Common::Path(src, '/').join("engines/cryomni3d/atlantis/con_exec.cpp"));
		Common::File f;
		TS_ASSERT(f.open(node));
		if (!f.isOpen())
			return;
		Common::Array<char> buf(f.size() + 1);
		f.read(buf.begin(), f.size());
		buf[f.size()] = 0;
		const char *st = strstr(buf.begin(), "\nbool CryOmni3DEngine_Atlantis::evalSelSection(");
		TS_ASSERT(st);
		if (!st)
			return;
		st++;
		const char *en = strstr(st, "\n}\n");
		TS_ASSERT(en);
		if (!en)
			return;
		en += 3;
		TS_ASSERT_EQUALS(AtlantisTest::md5Hex((const byte *)st, en - st),
		                 Common::String(ScriptsTest::kEvalSelSectionMd5));
	}

	// Synthetic cases, grouped by the behaviour they probe (indices into
	// kSynth).  Each group asserts that the port agrees with the original.
	void test_synth_operators()      { TS_ASSERT_EQUALS(runSynth(0, 8), 0u); }
	void test_synth_unsigned()       { TS_ASSERT_EQUALS(runSynth(8, 10), 0u); }
	void test_synth_value_parsing()  { TS_ASSERT_EQUALS(runSynth(10, 16), 0u); }
	void test_synth_key_lookup()     { TS_ASSERT_EQUALS(runSynth(16, 19), 0u); }
	void test_synth_unknown_key()    { TS_ASSERT_EQUALS(runSynth(19, 23), 0u); }
	void test_synth_and_or_chains()  { TS_ASSERT_EQUALS(runSynth(23, 41), 0u); }
	void test_synth_empty()          { TS_ASSERT_EQUALS(runSynth(41, 43), 0u); }
	void test_synth_inventory()      { TS_ASSERT_EQUALS(runSynth(43, 51), 0u); }
	void test_synth_table_size()     { TS_ASSERT_EQUALS(ARRAYSIZE(ScriptsEvalTest::kSynth), 51u); }

	uint runSynth(uint from, uint to) {
		uint fails = 0;
		for (uint i = from; i < to && i < ARRAYSIZE(ScriptsEvalTest::kSynth); i++) {
			const ScriptsEvalTest::SynthCase &c = ScriptsEvalTest::kSynth[i];
			ScriptsTest::VarState st;
			ScriptsEvalTest::stateFor(c, st);
			Common::Array<ScriptsTest::ConCondition> conds;
			ScriptsTest::portParseLine(c.text, conds);
			bool port = ScriptsTest::portEvalCopy(conds, st);
			if (port != c.expected) {
				fails++;
				TS_WARN(Common::String::format("scripts_con_eval: case %u '%s': original=%d port=%d",
				                               i, c.text, c.expected, port));
			}
		}
		return fails;
	}

	// Data test: every condition line of every CHAPI*.CON under 64
	// deterministic variable states; digest of the result bits per file.
	void test_data_conditions_match_original() {
		if (!AtlantisTest::haveData()) {
			TS_WARN("scripts_con_eval: no game data configured, skipped");
			return;
		}
		AtlantisTest::Golden golden;
		TS_ASSERT(AtlantisTest::loadGolden("scripts_con_eval.txt", golden));
		ScriptsTest::Big big;
		Common::Array<char> varias;
		TS_ASSERT(big.get("SCENAR\\VARIAS.CON", varias));
		Common::Array<Common::String> varNames;
		{
			Common::String cur;
			for (uint i = 0; i < varias.size(); i++) {
				char ch = varias[i];
				if (ch == '\r' || ch == '\n') {
					if (!cur.empty()) {
						cur.toLowercase();
						varNames.push_back(cur);
					}
					cur.clear();
				} else {
					cur += ch;
				}
			}
			if (!cur.empty()) {
				cur.toLowercase();
				varNames.push_back(cur);
			}
		}
		TS_ASSERT_EQUALS(varNames.size(), 77u);   // VARIAS.CON has 77 names
		Common::Array<Common::String> files = big.names("SCENAR\\CHAPI", ".CON");
		TS_ASSERT_EQUALS(files.size(), golden.size());
		uint mismatches = 0;
		Common::String list;
		for (uint f = 0; f < files.size(); f++) {
			Common::Array<char> data;
			TS_ASSERT(big.get(files[f], data));
			Common::Array<Common::String> lines;
			ScriptsTest::condLines(data, lines);
			Common::String bits;
			for (uint i = 0; i < lines.size(); i++) {
				Common::Array<ScriptsTest::ConCondition> conds;
				ScriptsTest::portParseLine(lines[i], conds);
				for (uint k = 0; k < 64; k++) {
					ScriptsTest::VarState st;
					ScriptsTest::makeState(i, k, varNames, lines[i], st);
					bits += ScriptsTest::portEvalCopy(conds, st) ? '1' : '0';
				}
			}
			Common::String key = files[f].substr(7);
			Common::String md5 = AtlantisTest::md5Hex((const byte *)bits.c_str(), bits.size());
			if (!golden.contains(key) || golden[key] != md5) {
				mismatches++;
				list += " " + key;
			}
		}
		if (mismatches)
			TS_WARN(Common::String::format("scripts_con_eval: %u files differ:", mismatches) + list);
		TS_ASSERT_EQUALS(mismatches, 0u);
	}
};

