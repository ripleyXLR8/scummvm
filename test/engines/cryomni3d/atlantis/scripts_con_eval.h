	// original checkpoints and the new game (no checkpoint): ArriveeVue and
	// the /sel section fired.  Expected: FUN_0042de5c then the head of
	// FUN_00423ad8 (ARRIVEEVUE != 0 @ 0x00423b48, FUN_00427548,
	// FUN_004280f8) run under emulation, golden scripts_arrival_after_load.txt
	// (atlantis-re tools/emu/scripts_arrival_after_load.py, experiment
	// 2026-10-15-93).  Port: arrivalAfterChapterLoad (the rule gameStep
	// applies after loadGame and the new game), findSelEntry and the real
	// ConEvaluator on the variables and inventory the original scan read.
	void test_arrival_after_load_vs_original() {
		using namespace CryOmni3D::Atlantis;
		if (!AtlantisTest::haveData()) {
			TS_WARN("arrival after load: no game data configured, skipped");
			return;
		}
		Common::Array<Common::String> lines;
		TS_ASSERT(AtlantisTest::loadGoldenLines("scripts_arrival_after_load.txt", lines));
		const ConVariableNames &names = ScriptsTest::variasNames();
		TS_ASSERT(!names.empty());
		if (lines.empty() || names.empty())
			return;
		ScriptsTest::Big big;
		Common::HashMap<Common::String, Common::String> varsLine, invLine;
		Common::Array<Common::String> ckLines;
		for (uint i = 0; i < lines.size(); i++) {
			const Common::String &l = lines[i];
			if (l.hasPrefix("CK "))
				ckLines.push_back(l);
			else if (l.hasPrefix("VARS ") || l.hasPrefix("INV ")) {
				const bool isVars = l.hasPrefix("VARS ");
				Common::String rest = l.substr(isVars ? 5 : 4);
				uint sp = rest.findFirstOf(' ');
				Common::String key = sp == Common::String::npos ? rest : rest.substr(0, sp);
				Common::String val = sp == Common::String::npos ? Common::String() : rest.substr(sp + 1);
				(isVars ? varsLine : invLine)[key] = val;
			}
		}
		TS_ASSERT_EQUALS(ckLines.size(), 75u);
		uint mismatches = 0;
		for (uint i = 0; i < ckLines.size(); i++) {
			// CK paN chapter C vue V lastvue L arriveevue A sel S alt 1 sel S'
			char name[16];
			int chapter = 0, vue = 0, lastVue = 0, arriveeOrig = 0;
			char selOrig[16];
			if (sscanf(ckLines[i].c_str(), "CK %15s chapter %d vue %d lastvue %d arriveevue %d sel %15s",
			           name, &chapter, &vue, &lastVue, &arriveeOrig, selOrig) != 6) {
				TS_FAIL(ckLines[i].c_str());
				continue;
			}
			const int expected = selOrig[0] == '-' ? -1 : atoi(selOrig);

			// The port's rule.
			int arrivee = -1;
			const bool scan = arrivalAfterChapterLoad((uint)lastVue, arrivee);
			if (arrivee != arriveeOrig)
				mismatches++;

			int got = -1;
			if (scan) {
				Common::Array<char> data;
				TS_ASSERT(big.get(Common::String::format("SCENAR\\CHAPI%03d.CON", chapter), data));
				ConScript script;
				script.parse(data.begin(), data.size());
				Common::HashMap<Common::String, int> vars;
				Common::Array<int> runs;
				const Common::String &vl = varsLine[name];
				for (uint p = 0; p < vl.size();) {
					uint e = p;
					while (e < vl.size() && vl[e] != ' ')
						e++;
					int idx = 0, v = 0;
					if (sscanf(vl.substr(p, e - p).c_str(), "%d:%d", &idx, &v) == 2)
						vars[names.name((uint)idx)] = v;
					p = e + 1;
				}
				vars["arriveevue"] = arrivee;
				ScriptsTest::VarState st;
				const Common::String &il = invLine[name];
				for (uint p = 0; p < il.size();) {
					uint e = p;
					while (e < il.size() && il[e] != ' ')
						e++;
					int id = 0, v = 0;
					if (sscanf(il.substr(p, e - p).c_str(), "%d:%d", &id, &v) == 2) {
						TS_ASSERT_EQUALS(v, 1);
						st.inventory.push_back(id);
					}
					p = e + 1;
				}
				st.vars = vars;
				struct Ctx {
					const ConScript *script;
					const ScriptsTest::VarState *st;
					static bool test(const ConSection &sec, void *ctx) {
						const Ctx *c = (const Ctx *)ctx;
						if (sec.condOffset < 0)
							return true;
						// The condition line as the scanner reads it.
						const Common::Array<char> &t = c->script->text();
						uint32 e = (uint32)sec.condOffset;
						while (e < t.size() && t[e] != '\r' && t[e] != '\n')
							e++;
						return ScriptsTest::portEval(Common::String(t.begin() + sec.condOffset, e - sec.condOffset), *c->st);
					}
				};
				Ctx ctx = { &script, &st };
				const int idx = findSelEntry(script, &Ctx::test, &ctx);
				got = idx < 0 ? -1 : script.sections()[idx].id;
			}
			if (got != expected) {
				mismatches++;
				warning("%s: port /sel %d, original %d", name, got, expected);
			}
		}
		TS_ASSERT_EQUALS(mismatches, 0u);
	}

	// ArriveeVue after a move into a sub-WAM: FUN_00423ad8 stores the place
	// being left (0x00423def), as on any move; the port used the arrived
	// place.  Golden scripts_subwam_arrival.txt (atlantis-re
	// tools/emu/scripts_subwam_arrival.py, experiment 2026-10-16-01): every
	// /sel line reading ARRIVEEVUE whose value changes for a reachable
	// sub-WAM move, with the original evaluator's 64 state bits for both
	// origins.  The port's ConEvaluator, given the place left (what
	// executeTransition now keeps), must give the original's bits; given the
	// destination, the old port's.
	void test_subwam_arrival_vs_original() {
		if (!AtlantisTest::haveData()) {
			TS_WARN("sub-WAM arrival: no game data configured, skipped");
			return;
		}
		Common::Array<Common::String> golden;
		TS_ASSERT(AtlantisTest::loadGoldenLines("scripts_subwam_arrival.txt", golden));
		ScriptsTest::Big big;
		Common::Array<char> varias;
		TS_ASSERT(big.get("SCENAR\\VARIAS.CON", varias));
		Common::Array<Common::String> varNames;
		{
			Common::String cur;
			for (uint i = 0; i <= varias.size(); i++) {
				const char ch = i < varias.size() ? varias[i] : '\n';
				if (ch == '\r' || ch == '\n') {
					if (!cur.empty()) {
						cur.toLowercase();
						varNames.push_back(cur);
					}
					cur.clear();
				} else {
					cur += ch;
				}
			}
		}
		uint rows = 0, mismatches = 0;
		for (uint g = 0; g < golden.size(); g++) {
			int chapter = 0, src = 0, dst = 0, lineIdx = 0;
			if (sscanf(golden[g].c_str(), "D chapter %d move %d->%d line %d", &chapter, &src, &dst, &lineIdx) != 4)
				continue;
			const uint o = golden[g].find(" orig="), p = golden[g].find(" port=");
			TS_ASSERT(o != Common::String::npos && p != Common::String::npos);
			const Common::String origBits = golden[g].substr(o + 6, 64), oldBits = golden[g].substr(p + 6, 64);
			Common::Array<char> data;
			TS_ASSERT(big.get(Common::String::format("SCENAR\\CHAPI%03d.CON", chapter), data));
			Common::Array<Common::String> lines;
			ScriptsTest::condLines(data, lines);
			TS_ASSERT((uint)lineIdx < lines.size());
			if ((uint)lineIdx >= lines.size())
				continue;
			Common::String fixedBits, prevBits;
			for (uint k = 0; k < 64; k++) {
				ScriptsTest::VarState st;
				ScriptsTest::makeState((uint)lineIdx, k, varNames, lines[lineIdx], st);
				st.vars["vue"] = dst;
				st.vars["arriveevue"] = src;      // the place left (the fix)
				fixedBits += ScriptsTest::portEval(lines[lineIdx], st) ? '1' : '0';
				st.vars["arriveevue"] = dst;      // the place arrived at (before)
				prevBits += ScriptsTest::portEval(lines[lineIdx], st) ? '1' : '0';
			}
			rows++;
			if (fixedBits != origBits || prevBits != oldBits) {
				mismatches++;
				warning("sub-WAM arrival: %s", golden[g].c_str());
			}
		}
		TS_ASSERT_EQUALS(rows, 17u);
		TS_ASSERT_EQUALS(mismatches, 0u);
	}

	// The sound on the moves whose video has a same-name APC (AT099100,
	// AT100099, AT110109, CP026126, CP030130, FO050051, SP026027: NewSound
	// entries 15..17, 98, 99, 108, 120), in every chapter where the move is
	// reachable: the original's departure scan FUN_004280f8 with VUE =
	// source, DEPARTVUE = CLICZONE = destination, ARRIVEEVUE = 0, over 64
	// states, and the NEWSOUND values the section found sets (golden
	// scripts_transition_sound.txt, atlantis-re
	// tools/emu/scripts_transition_sound.py, experiment 2026-10-16-08).  The
	// move itself plays no sound (FUN_00423ad8), which playTransitionVideo
	// now follows.  Port: findSelEntry with the real ConEvaluator, the
	// section's /set items and one /go.
	void test_transition_sound_vs_original() {
		using namespace CryOmni3D::Atlantis;
		if (!AtlantisTest::haveData()) {
			TS_WARN("transition sound: no game data configured, skipped");
			return;
		}
		Common::Array<Common::String> golden;
		TS_ASSERT(AtlantisTest::loadGoldenLines("scripts_transition_sound.txt", golden));
		ScriptsTest::Big big;
		Common::Array<char> varias;
		TS_ASSERT(big.get("SCENAR\\VARIAS.CON", varias));
		Common::Array<Common::String> varNames;
		{
			Common::String cur;
			for (uint i = 0; i <= varias.size(); i++) {
				const char ch = i < varias.size() ? varias[i] : '\n';
				if (ch == '\r' || ch == '\n') {
					if (!cur.empty()) {
						cur.toLowercase();
						varNames.push_back(cur);
					}
					cur.clear();
				} else {
					cur += ch;
				}
			}
		}
		uint rows = 0, states = 0, bad = 0;
		for (uint g = 0; g < golden.size(); g++) {
			int chapter = 0, src = 0, dst = 0, ref = 0;
			char apc[32];
			if (sscanf(golden[g].c_str(), "M chapter %d move %d->%d video-apc %31s ref %d:",
			           &chapter, &src, &dst, apc, &ref) != 5)
				continue;
			rows++;
			Common::Array<char> data;
			TS_ASSERT(big.get(Common::String::format("SCENAR\\CHAPI%03d.CON", chapter), data));
			ConScript script;
			script.parse(data.begin(), data.size());
			Common::Array<Common::String> lines;
			ScriptsTest::condLines(data, lines);
			const char *bar = strchr(golden[g].c_str(), '|');
			Common::Array<Common::String> want;
			for (const char *p = bar ? bar + 1 : ""; *p;) {
				while (*p == ' ')
					p++;
				const char *e = p;
				while (*e && *e != ' ')
					e++;
				if (e > p)
					want.push_back(Common::String(p, e - p));
				p = e;
			}
			TS_ASSERT_EQUALS(want.size(), 64u);
			for (uint k = 0; k < want.size(); k++) {
				ScriptsTest::VarState st;
				if (k == 0) {
					for (uint v = 0; v < varNames.size(); v++)
						st.vars[varNames[v]] = 0;
				} else {
					ScriptsTest::makeState((uint)ref, k, varNames, lines[ref], st);
				}
				st.vars["vue"] = src;
				st.vars["departvue"] = dst;
				st.vars["cliczone"] = dst;
				st.vars["arriveevue"] = 0;
				struct Ctx {
					const ConScript *script;
					const ScriptsTest::VarState *st;
					static bool test(const ConSection &sec, void *ctx) {
						const Ctx *c = (const Ctx *)ctx;
						if (sec.condOffset < 0)
							return true;
						const Common::Array<char> &t = c->script->text();
						uint32 e = (uint32)sec.condOffset;
						while (e < t.size() && t[e] != '\r' && t[e] != '\n')
							e++;
						return ScriptsTest::portEval(Common::String(t.begin() + sec.condOffset, e - sec.condOffset), *c->st);
					}
				};
				Ctx ctx = { &script, &st };
				const int idx = findSelEntry(script, &Ctx::test, &ctx);
				Common::String got = "-:-";
				if (idx >= 0) {
					ConSection sec = script.sections()[idx];
					const int id = sec.id;
					Common::String snd;
					for (uint hop = 0; hop < 2; hop++) {
						for (uint it = 0; it < sec.items.size(); it++)
							if (sec.items[it].isSet && scumm_strnicmp(sec.items[it].setCmd.c_str(), "newsound=", 9) == 0)
								snd += Common::String(snd.empty() ? "" : ",") +
								       Common::String::format("%d", atoi(sec.items[it].setCmd.c_str() + 9));
						if (hop == 0 && sec.gotoId > 0) {
							const int target = sec.gotoId;
							if (!script.gotoSection(target, sec))
								break;
						} else {
							break;
						}
					}
					got = Common::String::format("/%d:", id) + (snd.empty() ? Common::String("-") : snd);
				}
				states++;
				if (got != want[k]) {
					bad++;
					if (bad < 10)
						warning("transition sound: chapter %d move %d->%d state %u: port %s, original %s",
						        chapter, src, dst, k, got.c_str(), want[k].c_str());
				}
			}
		}
		TS_ASSERT(rows > 0);
		TS_ASSERT_EQUALS(states, rows * 64u);
		TS_ASSERT_EQUALS(bad, 0u);
	}

