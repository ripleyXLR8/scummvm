inline bool checkSynth(const char *name) {
	for (uint i = 0; i < ARRAYSIZE(kSynthCon); i++) {
		if (strcmp(kSynthCon[i].name, name))
			continue;
		ScriptsTest::ConScript script;
		script.parse(kSynthCon[i].text, strlen(kSynthCon[i].text));
		Common::String port = ScriptsTest::canonicalDump(script);
		if (port != kSynthCon[i].expected) {
			TS_WARN(Common::String::format("scripts_con_parse %s:\n--- original\n%s--- port\n%s",
			                               name, kSynthCon[i].expected, port.c_str()));
			return false;
		}
		return true;
	}
	TS_FAIL("unknown synthetic case");
	return false;
}

