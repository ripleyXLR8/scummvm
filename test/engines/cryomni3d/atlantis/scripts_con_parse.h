	// Data test: every SCENAR\CHAPI*.CON of the four discs.
	// /con play limits: entries the ORIGINAL /con scanner (FUN_004281f8)
	// finds with every play counter at 0, 1, 2 and 255 (atlantis-re
	// tools/emu/scripts_con_counts.py, an evaluator that always fails so
	// the whole file is walked); port: conEntryAllowed.
	void test_con_play_limits() {
		static const char *const kText =
		    "/1\r\n/con(ClicPerso=600)\r\n[Seth] A\r\n/2\r\n/con2(ClicPerso=600)\r\n[Seth] B\r\n"
		    "/3\r\n/con*(ClicPerso=600)\r\n[Seth] C\r\n/4\r\n/con300(ClicPerso=600)\r\n[Seth] D\r\n/000\r\n";
		static const struct { byte counter; const char *ids; } kOriginal[] = {
			{ 0, "1 2 3 4" }, { 1, "2 3 4" }, { 2, "3 4" }, { 255, "3 4" },
		};
		ScriptsTest::ConScript script;
		script.parse(kText, strlen(kText));
		for (uint c = 0; c < ARRAYSIZE(kOriginal); c++) {
			Common::Array<byte> counters(CryOmni3D::Atlantis::kConPlayCounterCount, kOriginal[c].counter);
			Common::String ids;
			for (uint i = 0; i < script.sections().size(); i++) {
				const ScriptsTest::ConSection &sec = script.sections()[i];
				if (!sec.isEntry || !sec.isCon || !CryOmni3D::Atlantis::conEntryAllowed(sec, counters))
					continue;
				if (!ids.empty())
					ids += " ";
				ids += Common::String::format("%d", sec.id);
			}
			TSM_ASSERT_EQUALS(Common::String::format("counter %u", kOriginal[c].counter).c_str(),
			                  ids, Common::String(kOriginal[c].ids));
		}
	}

	// Zone click / object in hand: the section the ORIGINAL FUN_00425cf4 runs
	// (atlantis-re tools/emu/scripts_click.py: real evaluator and /con
	// scanner, executor stubbed); 0 = none.  Port: findConClickEntry with the
	// real ConEvaluator.
	void test_con_click_entry() {
		if (!AtlantisTest::haveData()) {
			TS_WARN("scripts_con_parse: no game data configured (VARIAS.CON), skipped");
			return;
		}
		static const char *const kText =
		    "/1\r\n/con(ClicPerso=600)\r\n[Seth] npc\r\n"
		    "/2\r\n/con*(ClicZone=12)\r\n/suj3\r\n[Seth] subject\r\n"
		    "/3\r\n/con*(ClicZone=12)\r\n[Seth] zone 12\r\n"
		    "/4\r\n/con(ClicZone=12)&(FlagTemp1=1)\r\n[Seth] zone 12 flag\r\n"
		    "/5\r\n/con*(ObjetEnMain=300)\r\n[Seth] object\r\n"
		    "/000\r\n";
		static const struct { const char *name; const char *var1; int val1; const char *var2; int val2; byte counter; int section; } kOrig[] = {
			{ "zone12", "cliczone", 12, nullptr, 0, 0, 3 },
			{ "zone12_flag", "cliczone", 12, "flagtemp1", 1, 0, 3 },
			{ "zone13", "cliczone", 13, nullptr, 0, 0, 0 },
			{ "object300", "objetenmain", 300, nullptr, 0, 0, 5 },
			{ "npc600", "clicperso", 600, nullptr, 0, 0, 1 },
			{ "npc600_played", "clicperso", 600, nullptr, 0, 1, 0 },
		};
		struct Ctx {
			const Common::Array<char> *text;
			ScriptsTest::VarState st;
			static bool test(const ScriptsTest::ConSection &sec, void *ctx) {
				Ctx *c = (Ctx *)ctx;
				CryOmni3D::Inventory inv;
				ScriptsTest::NullInventoryCb cb;
				inv.init(1, new Common::Functor1Mem<uint, void, ScriptsTest::NullInventoryCb>(&cb, &ScriptsTest::NullInventoryCb::cb));
				CryOmni3D::Atlantis::ConEvaluator eval(ScriptsTest::variasNames(), c->st.vars, inv);
				return eval.evaluate(*c->text, (uint32)sec.condOffset);
			}
		};
		ScriptsTest::ConScript script;
		script.parse(kText, strlen(kText));
		for (uint i = 0; i < ARRAYSIZE(kOrig); i++) {
			Ctx ctx;
			ctx.text = &script.text();
			ctx.st.vars[kOrig[i].var1] = kOrig[i].val1;
			if (kOrig[i].var2)
				ctx.st.vars[kOrig[i].var2] = kOrig[i].val2;
			Common::Array<byte> counters(CryOmni3D::Atlantis::kConPlayCounterCount, kOrig[i].counter);
			int idx = CryOmni3D::Atlantis::findConClickEntry(script, counters, &Ctx::test, &ctx);
			int section = idx < 0 ? 0 : script.sections()[idx].id;
			TSM_ASSERT_EQUALS(kOrig[i].name, section, kOrig[i].section);
		}
	}

	void test_parse_matches_original_interpreter() {
		if (!AtlantisTest::haveData()) {
			TS_WARN("scripts_con_parse: no game data configured, skipped");
			return;
		}
		AtlantisTest::Golden golden;
		TS_ASSERT(AtlantisTest::loadGolden("scripts_con_parse.txt", golden));
		ScriptsTest::Big big;
		TS_ASSERT(!big.empty());
		Common::Array<Common::String> files = big.names("SCENAR\\CHAPI", ".CON");
		TS_ASSERT_EQUALS(files.size(), golden.size());
		Common::String dumpDir = AtlantisTest::configValue("scripts_dump");
		uint mismatches = 0;
		Common::String list;
		for (uint i = 0; i < files.size(); i++) {
			Common::Array<char> data;
			TS_ASSERT(big.get(files[i], data));
			ScriptsTest::ConScript script;
			script.parse(data.begin(), data.size());
			Common::String dump = ScriptsTest::canonicalDump(script);
			Common::String key = files[i].substr(7);       // "CHAPInnn.CON"
			Common::String md5 = AtlantisTest::md5Hex((const byte *)dump.c_str(), dump.size());
			if (!golden.contains(key) || golden[key] != md5) {
				mismatches++;
				list += " " + key;
			}
			if (!dumpDir.empty()) {
				Common::DumpFile df;
				Common::FSNode node(Common::Path(dumpDir, '/').appendComponent(key + ".txt"));
				if (df.open(node)) {
					df.write(dump.c_str(), dump.size());
					df.close();
				}
			}
		}
		if (mismatches)
			TS_WARN(Common::String::format("scripts_con_parse: %u files differ:", mismatches) + list);
		TS_ASSERT_EQUALS(mismatches, 0u);
	}

	// The track letter of every dialog line and game-over narrator: the
	// port's walk of each entry point (ConScript sections, /go through
	// gotoSection, conTrackLetter on the line index, the walk ending at a
	// gameover=N != 0 or a chapter=), against FUN_0042844c / FUN_00426590
	// run under emulation on every entry point of the 75 CHAPInnn.CON files
	// (golden video_dialog_letters.txt, atlantis-re
	// tools/emu/video_dialog_letters.py, experiment 2026-10-15-94).
	void test_track_letters_vs_original() {
		using namespace CryOmni3D::Atlantis;
		if (!AtlantisTest::haveData()) {
			TS_WARN("track letters: no game data configured, skipped");
			return;
		}
		Common::Array<Common::String> lines;
		TS_ASSERT(AtlantisTest::loadGoldenLines("video_dialog_letters.txt", lines));
		ScriptsTest::Big big;
		Common::HashMap<Common::String, ConScript *> scripts;
		uint walks = 0, dlg = 0, narr = 0, mismatches = 0;
		for (uint li = 0; li < lines.size(); li++) {
			const Common::String &l = lines[li];
			const bool isW = l.hasPrefix("W "), isG = l.hasPrefix("G ");
			if (!isW && !isG)
				continue;
			char con[16];
			int body = 0;
			if (sscanf(l.c_str() + 2, "%15s %d", con, &body) != 2) {
				TS_FAIL(l.c_str());
				continue;
			}
			if (!scripts.contains(con)) {
				Common::Array<char> data;
				TS_ASSERT(big.get(Common::String::format("SCENAR\\%s.CON", con), data));
				ConScript *s = new ConScript();
				s->parse(data.begin(), data.size());
				scripts[con] = s;
			}
			const ConScript &script = *scripts[con];
			const ConSection *start = nullptr;
			for (uint i = 0; i < script.sections().size() && !start; i++)
				if (script.sections()[i].bodyOffset == body)
					start = &script.sections()[i];
			if (!start) {
				mismatches++;
				warning("%s: no port section at body %d", con, body);
				continue;
			}
			// The port's walk: "<section><letter>" per line, and the
			// narrator's APC name at a game over.
			Common::String got, narrator;
			ConSection cur = *start;
			for (uint guard = 0; guard < 64; guard++) {
				uint lineIdx = 0;
				bool stop = false;
				for (uint k = 0; k < cur.items.size() && !stop; k++) {
					const ConSectionItem &it = cur.items[k];
					if (!it.isSet) {
						got += Common::String::format(" %d%c", cur.id, conTrackLetter(lineIdx++));
						continue;
					}
					if (scumm_strnicmp(it.setCmd.c_str(), "chapter=", 8) == 0) {
						stop = true;
					} else if (scumm_strnicmp(it.setCmd.c_str(), "gameover=", 9) == 0 &&
					           atoi(it.setCmd.c_str() + 9) != 0) {
						if (k + 1 < cur.items.size() && !cur.items[k + 1].isSet &&
						        cur.items[k + 1].line.speaker.hasPrefix("Narra"))
							narrator = Common::String::format("WAV\\ATA%04d%c.APC", cur.id,
							                                  conTrackLetter(lineIdx));
						stop = true;
					}
				}
				if (stop || cur.gotoId <= 0)
					break;
				const int target = cur.gotoId;
				if (!script.gotoSection(target, cur))
					break;
				cur.id = target;
			}
			if (isW) {
				walks++;
				// Expected: "<offset>:<section><letter>" tokens.
				Common::String want;
				const char *p = strchr(l.c_str(), ':');
				Common::String rest(p ? p + 1 : "");
				for (uint q = 0; q < rest.size();) {
					while (q < rest.size() && rest[q] == ' ')
						q++;
					uint e = q;
					while (e < rest.size() && rest[e] != ' ')
						e++;
					if (e > q) {
						Common::String tok = rest.substr(q, e - q);
						const char *c = strchr(tok.c_str(), ':');
						Common::String t(c ? c + 1 : tok.c_str());
						t.toUppercase();
						want += " " + t;
						dlg++;
					}
					q = e;
				}
				if (got != want) {
					mismatches++;
					warning("%s body %d: port%s, original%s", con, body, got.c_str(), want.c_str());
				}
			} else {
				narr++;
				// G <CON> <body> <section>: @<offset> narrator|no-narrator <apc>
				Common::String want;
				const char *p = strstr(l.c_str(), " narrator ");
				if (p)
					want = Common::String(p + 10);
				const uint sp = want.findFirstOf(' ');
				if (sp != Common::String::npos)
					want = want.substr(0, sp);
				want.toUppercase();
				if (want != narrator) {
					mismatches++;
					warning("%s body %d: port narrator '%s', original '%s'", con, body,
					        narrator.c_str(), want.c_str());
				}
			}
		}
		for (auto &kv : scripts)
			delete kv._value;
		TS_ASSERT_EQUALS(walks, 1197u);
		TS_ASSERT_EQUALS(dlg, 2797u);
		TS_ASSERT_EQUALS(narr, 364u);
		TS_ASSERT_EQUALS(mismatches, 0u);
	}

	// Escape during a talking-head line, after every played line of every
	// walk: the lines played after it, with their letters.  Expected:
	// FUN_0042844c with 0x00496134 set after line j (golden
	// video_dialog_escape.txt, atlantis-re tools/emu/video_dialog_escape.py,
	// experiment 2026-10-16-03).  Port: the walk of
	// test_track_letters_vs_original with conEscapeSkip after line j, as
	// playConSection runs it.
	void test_escape_skip_vs_original() {
		using namespace CryOmni3D::Atlantis;
		if (!AtlantisTest::haveData()) {
			TS_WARN("escape skip: no game data configured, skipped");
			return;
		}
		Common::Array<Common::String> lines;
		TS_ASSERT(AtlantisTest::loadGoldenLines("video_dialog_escape.txt", lines));
		ScriptsTest::Big big;
		Common::HashMap<Common::String, ConScript *> scripts;
		uint rows = 0, skipping = 0, mismatches = 0;
		for (uint li = 0; li < lines.size(); li++) {
			const Common::String &l = lines[li];
			if (!l.hasPrefix("E "))
				continue;
			char con[16], kind[8];
			int body = 0, sid = 0, escAt = 0, skipped = 0;
			if (sscanf(l.c_str() + 2, "%15s %d %7s %d esc %d skipped %d", con, &body, kind, &sid, &escAt, &skipped) != 6) {
				TS_FAIL(l.c_str());
				continue;
			}
			rows++;
			if (skipped)
				skipping++;
			if (!scripts.contains(con)) {
				Common::Array<char> data;
				TS_ASSERT(big.get(Common::String::format("SCENAR\\%s.CON", con), data));
				ConScript *s = new ConScript();
				s->parse(data.begin(), data.size());
				scripts[con] = s;
			}
			const ConScript &script = *scripts[con];
			const ConSection *start = nullptr;
			for (uint i = 0; i < script.sections().size() && !start; i++)
				if (script.sections()[i].bodyOffset == body)
					start = &script.sections()[i];
			if (!start) {
				mismatches++;
				continue;
			}
			Common::String got;
			int played = 0;
			ConSection cur = *start;
			for (uint guard = 0; guard < 64; guard++) {
				uint lineIdx = 0;
				bool stop = false;
				for (uint k = 0; k < cur.items.size() && !stop; k++) {
					const ConSectionItem &it = cur.items[k];
					if (!it.isSet) {
						if (played >= escAt)
							got += Common::String::format(" %d%c", cur.id, conTrackLetter(lineIdx));
						lineIdx++;
						if (++played == escAt)
							k = conEscapeSkip(cur.items, k + 1, lineIdx) - 1;
						continue;
					}
					if (scumm_strnicmp(it.setCmd.c_str(), "chapter=", 8) == 0 ||
					        (scumm_strnicmp(it.setCmd.c_str(), "gameover=", 9) == 0 && atoi(it.setCmd.c_str() + 9) != 0))
						stop = true;
				}
				if (stop || cur.gotoId <= 0)
					break;
				const int target = cur.gotoId;
				if (!script.gotoSection(target, cur))
					break;
				cur.id = target;
			}
			Common::String want;
			const char *p = strchr(l.c_str(), ':');
			Common::String rest(p ? p + 1 : "");
			for (uint q = 0; q < rest.size();) {
				while (q < rest.size() && rest[q] == ' ')
					q++;
				uint e = q;
				while (e < rest.size() && rest[e] != ' ')
					e++;
				if (e > q) {
					Common::String tok = rest.substr(q, e - q);
					const char *c = strchr(tok.c_str(), ':');
					Common::String t(c ? c + 1 : tok.c_str());
					t.toUppercase();
					want += " " + t;
				}
				q = e;
			}
			if (got != want) {
				mismatches++;
				if (mismatches <= 10)
					warning("%s body %d esc %d: port%s, original%s", con, body, escAt, got.c_str(), want.c_str());
			}
		}
		for (auto &kv : scripts)
			delete kv._value;
		TS_ASSERT_EQUALS(rows, 2797u);
		TS_ASSERT_EQUALS(skipping, 1546u);
		TS_ASSERT_EQUALS(mismatches, 0u);
	}
