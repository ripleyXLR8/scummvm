// ---- data tests: the shipped SPRLIST\*MENU.TXT files ------------------------

class UiMenusDataTestSuite : public CxxTest::TestSuite {
public:
	void setUp() override { Common::install_null_g_system(); }
	void tearDown() override { Common::uninstall_null_g_system(); }

private:
	static Common::String canonRects(const Common::Array<PortRec> &recs) {
		Common::String s;
		for (uint i = 0; i < recs.size(); i++) {
			if (i) s += ";";
			s += Common::String::format("%d,%d,%d,%d", recs[i].x, recs[i].y, recs[i].w, recs[i].h);
		}
		return s;
	}

	// FONTMAX.SPR glyph widths (sprite header word 0), parsed here; the port's
	// loadFontSpriteSet reads the same field into SubjSprite::w.
	static bool fontMaxWidths(CryOmni3D::Atlantis::BigFileArchive &big, Common::Array<int> &w) {
		Common::SeekableReadStream *s = big.createReadStreamForMember(Common::String("SPRITE\\2D\\FONTMAX.SPR"));
		if (!s)
			return false;
		uint16 flags = s->readUint16LE();
		if (flags & 4) s->skip(512);
		if (flags & 8) s->skip(512);
		uint16 count = s->readUint16LE();
		int64 base = s->pos();
		Common::Array<uint32> offs;
		for (uint i = 0; i < count; i++)
			offs.push_back(s->readUint32LE());
		for (uint i = 0; i < count; i++) {
			s->seek(base + offs[i]);
			w.push_back(s->readUint16LE());
		}
		delete s;
		return true;
	}

	// Glyph blits as drawSprFontText places them (sprFontPen with FONTMAX's
	// space advance 22 and kFontMaxMeasureWidths); labels per renderMenuLayout.
	static Common::String canonGlyphs(const Common::Array<int> &, const Common::Array<int> &glyphW,
	                                  const char *text, int menu, int a, int b) {
		CryOmni3D::Atlantis::MenuLayout layout;
		Common::MemoryReadStream st((const byte *)text, strlen(text));
		layout.loadFromStream(st);
		Common::String out;
		int toggleOrd = 0;
		for (uint i = 0; i < layout.items.size(); i++) {
			const CryOmni3D::Atlantis::MenuItem &it = layout.items[i];
			if (it.kind == CryOmni3D::Atlantis::MenuItem::kSprite)
				continue;
			Common::String label = it.text;
			if (it.kind == CryOmni3D::Atlantis::MenuItem::kToggle) {
				int sel = (menu == 2) ? portToggleSel(toggleOrd, a, b) : it.selected;
				toggleOrd++;
				label = it.options[sel];
			}
			Common::Array<CryOmni3D::Atlantis::SprFontGlyph> pen;
			CryOmni3D::Atlantis::sprFontPen(label, CryOmni3D::Atlantis::menuTextDrawX(it, label), 22, glyphW,
			                                CryOmni3D::Atlantis::kFontMaxMeasureWidths,
			                                ARRAYSIZE(CryOmni3D::Atlantis::kFontMaxMeasureWidths), pen);
			for (const CryOmni3D::Atlantis::SprFontGlyph &g : pen) {
				if (!out.empty()) out += ";";
				out += Common::String::format("%d,%d,%d", g.x, it.anchorY, g.idx);
			}
		}
		return out;
	}

	static Common::String canonSprites(const char *text) {
		CryOmni3D::Atlantis::MenuLayout layout;
		Common::MemoryReadStream st((const byte *)text, strlen(text));
		layout.loadFromStream(st);
		Common::String out;
		for (uint i = 0; i < layout.items.size(); i++) {
			const CryOmni3D::Atlantis::MenuItem &it = layout.items[i];
			if (it.kind != CryOmni3D::Atlantis::MenuItem::kSprite)
				continue;
			if (!out.empty()) out += ";";
			out += Common::String::format("%d,%d,%d", it.hx, it.hy, it.sprIdx);
		}
		return out;
	}

	static Common::String md5(const Common::String &s) {
		return AtlantisTest::md5Hex((const byte *)s.c_str(), s.size());
	}

	void run(const char *what) {
		if (!AtlantisTest::haveData()) {
			TS_WARN("Atlantis data not configured; ui_menus data tests skipped");
			return;
		}
		Common::Array<int> tbl = portFontMaxTable();
		AtlantisTest::Golden golden;
		TS_ASSERT(AtlantisTest::loadGolden("ui_menus.txt", golden));
		// BigFileArchive::open goes through SearchMan.
		SearchMan.addDirectory("ui_menus_data", Common::FSNode(Common::Path(AtlantisTest::dataDir(), '/')));
		CryOmni3D::Atlantis::BigFileArchive big;
		bool opened = big.open(Common::Path("BIGCD1.BIG"));
		SearchMan.remove("ui_menus_data");
		TS_ASSERT(opened);
		if (!opened)
			return;
		Common::Array<int> glyphW;
		TS_ASSERT(fontMaxWidths(big, glyphW));
		static const char *const files[] = {
			"MAINMENU", "LOADMENU", "OPTMENU", "NEWMENU", "SELEMENU", "SONMENU",
			"SUREMENU", "CD1MENU", "CD2MENU", "CD3MENU", "CD4MENU", "WAIT",
			"ERROR1", "ERROR2", "ERROR3" };
		for (uint f = 0; f < ARRAYSIZE(files); f++) {
			Common::String name = Common::String(files[f]) + ".TXT";
			Common::SeekableReadStream *s = big.createReadStreamForMember("SPRLIST\\" + name);
			TSM_ASSERT(name.c_str(), s != nullptr);
			if (!s)
				continue;
			Common::String text;
			while (!s->eos()) {
				char c;
				if (s->read(&c, 1) == 1)
					text += c;
			}
			delete s;
			int nstates = (f == 2) ? 4 : 1;
			for (int st = 0; st < nstates; st++) {
				int a = (st >> 1) & 1, b = st & 1;
				Common::String suf = (f == 2) ? Common::String::format(".t%d%d", a, b) : Common::String();
				Common::String key = name + "." + what + suf;
				Common::String got;
				if (!strcmp(what, "rects")) {
					Common::Array<PortRec> recs;
					portRecords(tbl, text.c_str(), (int)f, a, b, recs);
					got = canonRects(recs);
				} else if (!strcmp(what, "glyphs")) {
					got = canonGlyphs(tbl, glyphW, text.c_str(), (int)f, a, b);
				} else {
					got = canonSprites(text.c_str());
				}
				TSM_ASSERT(key.c_str(), golden.contains(key));
				if (golden.contains(key))
					TSM_ASSERT_EQUALS(key.c_str(), md5(got), golden[key]);
			}
		}
	}

public:
	// Hit tables of every shipped menu (port parse + menuTextHitRect).
	void test_shipped_menu_hit_tables() { run("rects"); }
	// SPRMENU sprite blits (index and hotspot) of every shipped menu.
	void test_shipped_menu_sprites() { run("sprites"); }
	// FONTMAX glyph blits: the original advances the pen by the exe width
	// table (0x49660e); so does the port (drawSprFontText with
	// kFontMaxMeasureWidths), no longer by the FONTMAX.SPR sprite width.
	void test_shipped_menu_glyph_positions() { run("glyphs"); }
};
