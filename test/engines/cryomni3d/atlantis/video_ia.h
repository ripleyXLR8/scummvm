	// Every frame of every UBB: the port decoder's CLUT8 frame, palette and
	// captured IA stream, composited by portCompose, against FUN_00450b08.
	void test_ubb_composite_data() {
		using namespace VideoIa;
		if (!AtlantisTest::haveData()) {
			TS_WARN("Atlantis data not configured: UBB composite test skipped");
			return;
		}
		AtlantisTest::Golden golden;
		if (!AtlantisTest::loadGolden("video_ia_composite.txt", golden)) {
			TS_FAIL("video_ia_composite.txt missing from the configured golden directory");
			return;
		}
		VideoTest::Big big;
		Common::Array<Common::String> ubbs = big.names(".UBB");
		TS_ASSERT_EQUALS(ubbs.size(), 124u);
		uint16 *bg = new uint16[N];
		uint16 *dst = new uint16[N];
		byte *flat = new byte[N];
		background(bg);
		int frames = 0, badStandin = 0, badReal = 0, noOps = 0;
		Common::String firstStandin, firstReal;
		for (uint u = 0; u < ubbs.size(); u++) {
			uint32 size = 0;
			byte *data = big.get(ubbs[u], size);
			uint32 nframes = READ_LE_UINT32(data + 0x10);
			Common::String base = strrchr(ubbs[u].c_str(), '\\') + 1;
			WRITE_LE_UINT32(data + 0x18, 0);   // no audio track, see video_hnm.h
			Video::HNMDecoder dec(Graphics::PixelFormat::createFormatCLUT8(), true);
			dec.loadStream(new Common::MemoryReadStream(data, size, DisposeAfterUse::YES));
			dec.setCaptureOpcodeStream(true);
			byte pal[768];
			memset(pal, 0, sizeof(pal));
			for (uint32 fi = 0; fi < nframes; fi++) {
				const Graphics::Surface *f = dec.decodeNextFrame();
				if (dec.hasDirtyPalette())
					memcpy(pal, dec.getPalette(), 768);
				for (int y = 0; y < 480; y++)
					memcpy(flat + y * 640, f->getBasePtr(0, y), 640);
				uint32 opSize = 0;
				const byte *ops = dec.getOpcodeStream(opSize);
				if (!ops || opSize < 4) {
					noOps++;
					continue;
				}
				uint16 lut[256];
				portLut(pal, lut);
				frames++;
				for (int pass = 0; pass < 2; pass++) {
					memcpy(dst, bg, N * 2);
					portCompose(dst, flat, lut, ops, opSize, pass ? portBlend : standinBlend);
					Common::String key = Common::String::format("%s#%u#%s", base.c_str(), fi,
					                                            pass ? "real" : "standin");
					if (!golden.contains(key) || golden[key] != md5Le16(dst, N)) {
						if (pass) { badReal++; if (firstReal.empty()) firstReal = key; }
						else { badStandin++; if (firstStandin.empty()) firstStandin = key; }
					}
				}
			}
		}
		delete[] bg;
		delete[] dst;
		delete[] flat;
		TS_WARN(Common::String::format("UBB composite: %d frames, %d without IA stream; "
		        "walk (stand-in blend) differs on %d (first %s); real blend differs on %d (first %s)",
		        frames, noOps, badStandin, firstStandin.c_str(), badReal, firstReal.c_str()).c_str());
		// Every frame of the golden (a stand-in and a real key each) compared.
		TS_ASSERT(frames > 0);
		TS_ASSERT_EQUALS(frames, (int)golden.size() / 2);
		TS_ASSERT_EQUALS(noOps, 0);
		TS_ASSERT_EQUALS(badStandin, 0);
		TS_ASSERT_EQUALS(badReal, 0);
	}
