	void compose(bool real, const char *expected) {
		using namespace VideoIa;
		byte pal[768];
		byte *src = new byte[N];
		uint16 *dst = new uint16[N];
		Common::Array<byte> ops;
		synthInputs(pal, src, ops);
		uint16 lut[256];
		portLut(pal, lut);
		background(dst);
		portCompose(dst, src, lut, ops.data(), ops.size(), real ? portBlend : standinBlend);
		TS_ASSERT_EQUALS(md5Le16(dst, N), Common::String(expected));
		delete[] src;
		delete[] dst;
	}

